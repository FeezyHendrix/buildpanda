import { TrendingUp } from "lucide-react";
import { useProjectContext } from "@/layouts/project-layout";
import { useSetPageTitle } from "@/contexts/page-title-context";
import { useLatestInsight, useAnalyzeProject } from "@/hooks/use-panda-ai";
import { useReportingSnapshot } from "@/hooks/use-reporting-snapshot";
import { Button } from "@/components/atoms/button";
import { Spinner } from "@/components/atoms/spinner";
import { EmptyState } from "@/components/molecules/empty-state";
import { HealthScoreCard, HealthTrendCard, SummaryCard } from "./panda-ai/health-cards";
import { MetricsOverview } from "./panda-ai/metrics-overview";
import { SuggestionsList } from "./panda-ai/suggestions-list";

export default function ProjectPandaAi() {
  useSetPageTitle("Panda AI Hub", "Project health, key metrics and prioritised suggestions from Panda AI.");
  const { project } = useProjectContext();
  const { data: insight, isPending } = useLatestInsight(project.id);
  const { data: reportingData } = useReportingSnapshot(project.id);
  const analyze = useAnalyzeProject();
  const trend = reportingData?.health.trendOldestFirst ?? [];

  function handleAnalyze() {
    analyze.mutate(project.id);
  }

  const isAnalyzing =
    analyze.isPending ||
    insight?.status === "pending" ||
    insight?.status === "processing" ||
    (!insight && isPending);

  return (
    <div className="w-full px-4 pb-24 pt-6 lg:px-8">
      <div className="flex justify-end">
        <Button variant="primary" size="md" onClick={handleAnalyze} disabled={isAnalyzing}>
          <TrendingUp className="size-4" />
          Run Analysis
        </Button>
      </div>

      {isAnalyzing ? (
        <div className="flex h-64 flex-col items-center justify-center space-y-4">
          <Spinner size="md" />
          <p className="text-caption-l! text-gray-500">Panda AI is analyzing project data...</p>
        </div>
      ) : !insight ? (
        <EmptyState
          title="No analysis yet"
          description="Run your first Panda AI analysis to get prioritized suggestions and health metrics."
          action={{ label: "Run first analysis", onClick: handleAnalyze }}
        />
      ) : insight.status === "failed" ? (
        <EmptyState
          title="Analysis failed"
          description={insight.error || "An error occurred while generating the analysis."}
          action={{ label: "Try again", onClick: handleAnalyze }}
        />
      ) : (
        <div className="mt-6 grid gap-6">
          <div className="grid grid-cols-1 gap-6 md:grid-cols-2">
            <HealthScoreCard score={insight.healthScore} />
            <SummaryCard summary={insight.summary} />
          </div>

          {trend.length >= 2 ? <HealthTrendCard points={trend} /> : null}

          <MetricsOverview insight={insight} currency={project.currency} />

          <section className="mt-5">
            <h2 className="mb-4 text-h6 font-semibold text-black-500">Prioritised Suggestions</h2>
            <SuggestionsList suggestions={insight.suggestions} />
          </section>

          <div className="mt-4 flex items-center justify-between text-xs text-gray-400">
            <p>{insight.model ? `Generated by ${insight.model}` : "AI Analysis"}</p>
            <p>Last updated: {new Date(insight.updatedAt).toLocaleString("en-GB")}</p>
          </div>
        </div>
      )}
    </div>
  );
}
